import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const checkMode = process.argv.includes("--check");
const fixtureDir = "fixtures/021-large-performance";
const files = {
  expectations: `${fixtureDir}/expectations.md`,
  input: `${fixtureDir}/input.md`
};
const sectionCount = 320;

const generated = {
  [files.input]: renderInput(),
  [files.expectations]: renderExpectations()
};

if (checkMode) {
  for (const [path, content] of Object.entries(generated)) {
    const committed = existsSync(path) ? await readFile(path, "utf8") : "";
    if (committed !== content) {
      throw new Error(`${path} is out of sync. Run: node scripts/generate-large-performance-fixture.mjs`);
    }
  }
} else {
  await mkdir(fixtureDir, { recursive: true });
  for (const [path, content] of Object.entries(generated)) {
    await writeFile(path, content);
  }
}

function renderInput() {
  const lines = [
    "---",
    "title: Large Performance Fixture",
    "fixture: 021-large-performance",
    "generated: true",
    "safe: sanitized",
    "---",
    "",
    "# Large Performance Fixture",
    "",
    "This generated document is intentionally large and structurally varied.",
    "It proves performance budgets against real Markdown shapes instead of a repeated single-line mock.",
    ""
  ];

  for (let index = 1; index <= sectionCount; index += 1) {
    const id = String(index).padStart(4, "0");
    const variant = index % 4;
    lines.push(
      `## Performance section ${id}`,
      "",
      `Paragraph ${id} links to [relative link](./section-${id}.md), uses [[Performance ${id}]], and cites [^perf-${id}].`,
      `It keeps **bold text**, _underscore emphasis_, inline \`code-${id}\`, and a safe email placeholder user-${id}@example.test.`,
      "",
      `- [ ] Todo item ${id}`,
      `- [x] Completed item ${id}`,
      `  - Nested bullet ${id}`,
      `  - Nested link [child ${id}](./child-${id}.md)`,
      "",
      "1. First ordered step",
      "2. Second ordered step",
      ""
    );

    if (variant === 0) {
      lines.push(
        `### Nested checkpoint ${id}`,
        "",
        `This subsection adds nested outline pressure for section ${id}.`,
        ""
      );
    } else if (variant === 1) {
      lines.push(
        `> Quote variant ${id}`,
        `> - quoted task ${id}`,
        `> - quoted link [variant ${id}](./variant-${id}.md)`,
        ""
      );
    } else if (variant === 2) {
      lines.push(
        `<aside data-mme-variant="${id}">Inline HTML variant ${id} with <strong>safe emphasis</strong>.</aside>`,
        ""
      );
    } else {
      lines.push(
        `![Generated diagram ${id}](./assets/performance-${id}.png "Synthetic performance asset")`,
        ""
      );
    }

    lines.push(
      "| Metric | Value | Notes |",
      "| -- | --: | -- |",
      `| Parse | ${index} | section ${id} |`,
      `| Render | ${index * 2} | preserves pipes \\| and links |`,
      "",
      `> [!NOTE] Section ${id}`,
      `> Callout body for performance section ${id}.`,
      "",
      "```ts",
      `export const section${id} = {`,
      `  id: "${id}",`,
      `  markdownSource: "durable",`,
      "};",
      "```",
      "",
      "```mermaid",
      "graph TD",
      `  A${id}[Markdown] --> B${id}[Derived view]`,
      `  B${id} --> C${id}[Saved source]`,
      "```",
      "",
      `<section data-mme-performance="${id}">`,
      `  <p>Safe HTML block ${id} remains an artifact or preserved source.</p>`,
      "</section>",
      "",
      `::mme-opaque{#perf-${id}}`,
      `custom payload ${id} must stay source-only unless a host extension understands it.`,
      "::",
      "",
      `[^perf-${id}]: Generated footnote ${id} with a [back reference](#performance-section-${id}).`,
      ""
    );
  }

  return `${lines.join("\n")}\n`;
}

function renderExpectations() {
  return [
    "# Fixture 021 — Large Performance",
    "",
    "This 10k-line fixture is generated by `scripts/generate-large-performance-fixture.mjs`.",
    "",
    "Expected behavior:",
    "",
    "- Preserve Markdown source outside the edited range.",
    "- Keep generated frontmatter normalized and intact.",
    "- Preserve opaque `::mme-opaque` blocks as source-only syntax.",
    "- Render supported Markdown, GFM tables, footnotes, callouts, code fences, Mermaid fences, links, and safe HTML without crashing.",
    "- Use this fixture for performance guardrails, not as a public benchmark claim.",
    "",
    "The content is synthetic and sanitized; it must not contain private data, real credentials, or real user documents.",
    ""
  ].join("\n");
}
